import {readFile,writeFile,mkdir,cp,rm} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
const root=path.dirname(fileURLToPath(import.meta.url));
const dist=path.join(root,'dist');
const manifest=JSON.parse(await readFile(path.join(root,process.env.ACE_DOWNLOAD_MANIFEST || 'download.json'),'utf8'));
if(!/^[a-f0-9]{64}$/.test(manifest.sha256)||!/^https:\/\/github\.com\/MphoCodes\/AceTimeTracker\/releases\/download\//.test(manifest.url)||!/^[-\w.]+\.apk$/.test(manifest.filename)) throw Error('Invalid pinned APK manifest');
const response=await fetch(manifest.url,{signal:AbortSignal.timeout(120000)});
if(!response.ok) throw Error(`APK download failed: ${response.status}`);
const apk=Buffer.from(await response.arrayBuffer());
if(createHash('sha256').update(apk).digest('hex')!==manifest.sha256) throw Error('APK SHA-256 mismatch; build stopped');
if(manifest.sizeBytes && apk.length!==manifest.sizeBytes) throw Error('APK size differs from manifest');
await rm(dist,{recursive:true,force:true});
await mkdir(path.join(dist,'downloads'),{recursive:true});
await cp(path.join(root,'public'),dist,{recursive:true});
await mkdir(path.join(dist,'assets'),{recursive:true});
const docs=path.join(root,'../docs');
for(const name of ['today','timer','history','add-time','reports']) await cp(path.join(docs,`demo/film/assets/${name}.png`),path.join(dist,`assets/${name}.png`));
await cp(path.join(docs,'brand/ace-mark.svg'),path.join(dist,'assets/ace-mark.svg'));
await cp(path.join(docs,'demo/acetimetracker-demo.mp4'),path.join(dist,'assets/ace-demo.mp4'));
await cp(path.join(docs,'demo/acetimetracker-demo.jpg'),path.join(dist,'assets/ace-demo.jpg'));
const srt=await readFile(path.join(docs,'demo/acetimetracker-demo.srt'),'utf8');
await writeFile(path.join(dist,'assets/ace-demo.vtt'),'WEBVTT\n\n'+srt.replace(/(\d{2}:\d{2}:\d{2}),(\d{3})/g,'$1.$2'));
await writeFile(path.join(dist,'downloads',manifest.filename),apk);
await writeFile(path.join(dist,'downloads/SHA256SUMS.txt'),`${manifest.sha256}  ${manifest.filename}\n`);
await writeFile(path.join(dist,'download.json'),JSON.stringify({...manifest,url:`/downloads/${manifest.filename}`},null,2));
const escape=s=>String(s).replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
let page=await readFile(path.join(dist,'index.html'),'utf8');
for(const [key,value] of Object.entries({version:manifest.version,filename:manifest.filename,size:`${(apk.length/1000000).toFixed(1)} MB`,minimumAndroid:manifest.minimumAndroid})) page=page.replaceAll(`{{${key}}}`,escape(value));
await writeFile(path.join(dist,'index.html'),page);
console.log(`Built ${manifest.version}; verified ${apk.length} APK bytes and copied current film/captions.`);
